<h2>What is Paralysis?</h2>
<p>Paralysis refers to the loss of muscle function in one or more parts of the body. It occurs when communication between the brain, spinal cord, and muscles is disrupted due to damage to the nervous system.</p>
<p>Paralysis may affect:</p>
<ul>
    <li>One side of the body</li>
    <li>Both legs</li>
    <li>One arm or leg</li>
    <li>Facial muscles</li>
    <li>Entire body in severe conditions</li>
</ul>
<p>The condition can be temporary or permanent depending on the cause and severity.</p>

<h2>Common Causes of Paralysis</h2>
<h3>1. Stroke</h3>
<p>Stroke is one of the most common causes of paralysis. Reduced blood supply to the brain can damage brain cells responsible for movement and coordination.</p>
<h3>2. Spinal Cord Injury</h3>
<p>Accidents, trauma, or injuries to the spinal cord can interrupt nerve signals and cause paralysis.</p>
<h3>3. Brain Injury</h3>
<p>Severe head injuries may affect the areas of the brain that control body movements.</p>
<h3>4. Neurological Disorders</h3>
<p>Conditions like multiple sclerosis, Guillain-Barre syndrome, and motor neuron disease can lead to muscle weakness and paralysis.</p>
<h3>5. Infections</h3>
<p>Certain infections affecting the brain or spinal cord may also result in paralysis.</p>

<h2>Symptoms of Paralysis</h2>
<p>Common symptoms include:</p>
<ul>
    <li>Sudden weakness in arms or legs</li>
    <li>Loss of movement</li>
    <li>Difficulty walking</li>
    <li>Numbness or tingling</li>
    <li>Facial drooping</li>
    <li>Difficulty speaking</li>
    <li>Loss of bladder or bowel control</li>
    <li>Muscle stiffness or spasms</li>
</ul>

<h2>Types of Paralysis</h2>
<h3>Monoplegia</h3><p>Paralysis affecting one limb.</p>
<h3>Hemiplegia</h3><p>Paralysis affecting one side of the body, commonly seen after stroke.</p>
<h3>Paraplegia</h3><p>Paralysis affecting both legs and lower body.</p>
<h3>Quadriplegia</h3><p>Paralysis affecting all four limbs and the body below the neck.</p>

