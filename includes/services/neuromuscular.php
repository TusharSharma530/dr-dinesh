<h2>Treatment Options</h2>
<h3>Medications</h3>
<p>Immunosuppressants, steroids, and other medications may be prescribed.</p>
<h3>Physiotherapy</h3>
<p>Physical therapy helps maintain muscle strength, flexibility, and mobility.</p>
<h3>Occupational Therapy</h3>
<p>Helps patients adapt to daily activities and maintain independence.</p>

