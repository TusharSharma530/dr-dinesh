<h2>Stroke Treatment Options</h2>
<h3>Medications</h3>
<p>Blood clot-busting drugs (tPA), antiplatelet medicines, and anticoagulants may be prescribed.</p>
<h3>Surgery</h3>
<p>In severe cases, surgical procedures like carotid endarterectomy or stenting may be required.</p>
<h3>Physiotherapy & Rehabilitation</h3>
<p>Physical therapy, occupational therapy, and speech therapy help patients recover.</p>
<h3>Lifestyle Changes</h3>
<p>Managing blood pressure, quitting smoking, exercising regularly, and eating a healthy diet.</p>

<h2>Can Stroke Be Recovered?</h2>
<p>Recovery depends on type and severity of stroke, how quickly treatment was started, patient's age and overall health, and rehabilitation support.</p>

<h2>Tips to Prevent Stroke</h2>
<ul>
    <li>Control high blood pressure</li>
    <li>Manage diabetes and cholesterol</li>
    <li>Quit smoking and limit alcohol</li>
    <li>Exercise regularly</li>
    <li>Maintain a healthy weight</li>
    <li>Eat a balanced diet rich in fruits and vegetables</li>
</ul>

