<h2>What is Stroke?</h2>
<p>A stroke happens when the blood supply to a part of the brain is blocked or when a blood vessel in the brain bursts. This deprives brain tissue of oxygen and nutrients, causing brain cells to die.</p>
<p>Stroke can affect:</p>
<ul>
    <li>Movement and coordination</li>
    <li>Speech and language</li>
    <li>Vision</li>
    <li>Memory and thinking</li>
    <li>Emotional control</li>
</ul>

<h2>Types of Stroke</h2>
<h3>1. Ischemic Stroke</h3>
<p>The most common type, caused by a blockage in an artery supplying blood to the brain.</p>
<h3>2. Hemorrhagic Stroke</h3>
<p>Occurs when a blood vessel in the brain bursts, causing bleeding in or around the brain.</p>
<h3>3. Transient Ischemic Attack (TIA)</h3>
<p>Also known as a mini-stroke, TIA is a temporary blockage of blood flow to the brain.</p>

<h2>Common Causes of Stroke</h2>
<h3>1. High Blood Pressure</h3>
<p>The leading cause of stroke. Uncontrolled hypertension damages blood vessels over time.</p>
<h3>2. Diabetes</h3>
<p>People with diabetes have a higher risk of stroke due to damaged blood vessels.</p>
<h3>3. Heart Disease</h3>
<p>Conditions like atrial fibrillation can cause blood clots that travel to the brain.</p>
<h3>4. Smoking</h3>
<p>Smoking damages blood vessels and raises blood pressure, increasing stroke risk.</p>
<h3>5. High Cholesterol</h3>
<p>Excess cholesterol can build up in arteries, blocking blood flow to the brain.</p>

<h2>Symptoms of Stroke</h2>
<p>Remember the acronym <strong>BE FAST</strong> to recognize stroke symptoms:</p>
<ul>
    <li><strong>B</strong>alance – Sudden loss of balance or coordination</li>
    <li><strong>E</strong>yes – Sudden vision changes in one or both eyes</li>
    <li><strong>F</strong>ace – Facial drooping on one side</li>
    <li><strong>A</strong>rms – Weakness or numbness in one arm</li>
    <li><strong>S</strong>peech – Slurred or difficulty speaking</li>
    <li><strong>T</strong>ime – Time to call emergency immediately</li>
</ul>

