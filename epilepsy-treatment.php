            <h2>What is Epilepsy?</h2>
            <p>Epilepsy is a brain disorder in which nerve cells in the brain signal abnormally, causing seizures. A seizure is a sudden surge of electrical activity in the brain that temporarily affects how the brain works.</p>
            <p>Epilepsy may affect:</p>
            <ul>
                <li>Consciousness and awareness</li>
                <li>Movement and coordination</li>
                <li>Sensation and emotions</li>
                <li>Behavior and memory</li>
            </ul>
            <p>Seizures can vary from brief lapses of attention to full-body convulsions lasting several minutes.</p>

            <h2>Types of Seizures</h2>

            <h3>1. Focal Seizures (Partial Seizures)</h3>
            <p>Occur in one area of the brain. Symptoms may include confusion, jerking movements, or unusual sensations.</p>

            <h3>2. Generalized Seizures</h3>
            <p>Affect both sides of the brain. Types include:</p>
            <ul>
                <li><strong>Absence Seizures</strong> – Brief staring spells</li>
                <li><strong>Tonic-Clonic Seizures</strong> – Convulsions with stiffening and jerking</li>
                <li><strong>Myoclonic Seizures</strong> – Brief jerking of arms or legs</li>
                <li><strong>Atonic Seizures</strong> – Sudden loss of muscle tone</li>
            </ul>

            <h2>Common Causes of Epilepsy</h2>

            <h3>1. Genetic Factors</h3>
            <p>Some types of epilepsy run in families and are linked to genetic changes.</p>

            <h3>2. Brain Injury</h3>
            <p>Trauma from accidents, falls, or head injuries can trigger epilepsy.</p>

            <h3>3. Infections</h3>
            <p>Meningitis, encephalitis, and other brain infections may lead to epilepsy.</p>

            <h3>4. Stroke</h3>
            <p>Stroke is a common cause of epilepsy in older adults.</p>

            <h3>5. Brain Tumors</h3>
            <p>Growths in the brain can cause abnormal electrical activity.</p>

            <h3>6. Developmental Disorders</h3>
            <p>Conditions like autism and neurofibromatosis are associated with epilepsy.</p>

            <h2>Symptoms of Epilepsy</h2>
            <p>Symptoms depend on the type of seizure:</p>
            <ul>
                <li>Temporary confusion</li>
                <li>Staring spells</li>
                <li>Uncontrollable jerking movements</li>
                <li>Loss of consciousness</li>
                <li>Psychic symptoms like fear or anxiety</li>
                <li>Difficulty speaking</li>
                <li>Unusual sensations</li>
            </ul>
            <p>If seizures recur without a known cause, immediate neurological consultation is recommended.</p>

