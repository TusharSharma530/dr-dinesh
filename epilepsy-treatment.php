            <h2>Epilepsy Treatment Options</h2>

            <h3>Medications</h3>
            <p>Anti-epileptic drugs (AEDs) are the most common treatment. They help control seizures in about 70% of patients.</p>

            <h3>Surgery</h3>
            <p>For drug-resistant epilepsy, surgery may be recommended to remove the area of the brain causing seizures.</p>

            <h3>Vagus Nerve Stimulation (VNS)</h3>
            <p>A device implanted in the chest sends electrical signals to the brain to reduce seizure frequency.</p>

            <h3>Ketogenic Diet</h3>
            <p>A high-fat, low-carbohydrate diet that may help control seizures, especially in children.</p>

            <h3>Lifestyle Changes</h3>
            <p>Regular sleep, stress management, and avoiding seizure triggers are important for seizure control.</p>

