            <h2>Types of Sleep Disorders</h2>

            <h3>1. Insomnia</h3>
            <p>Difficulty falling asleep, staying asleep, or waking up too early. It can be short-term or chronic.</p>

            <h3>2. Sleep Apnea</h3>
            <p>A serious condition where breathing repeatedly stops and starts during sleep. Obstructive sleep apnea is the most common type.</p>

            <h3>3. Restless Leg Syndrome (RLS)</h3>
            <p>An uncontrollable urge to move the legs, usually due to uncomfortable sensations. Symptoms worsen at night.</p>

            <h3>4. Narcolepsy</h3>
            <p>A neurological disorder that causes excessive daytime sleepiness and sudden sleep attacks.</p>

            <h3>5. Parasomnias</h3>
            <p>Abnormal behaviors during sleep such as sleepwalking, sleep talking, and night terrors.</p>

            <h3>6. Circadian Rhythm Disorders</h3>
            <p>Disruptions in the body's internal clock that affect sleep-wake timing.</p>

            <h2>Common Causes of Sleep Disorders</h2>

            <h3>1. Stress and Anxiety</h3>
            <p>Emotional stress is one of the most common causes of sleep problems.</p>

            <h3>2. Medical Conditions</h3>
            <p>Chronic pain, asthma, heart disease, and neurological conditions can disrupt sleep.</p>

            <h3>3. Medications</h3>
            <p>Side effects of certain medications may interfere with sleep.</p>

            <h3>4. Poor Sleep Habits</h3>
            <p>Irregular sleep schedule, screen time before bed, and caffeine intake can affect sleep quality.</p>

            <h3>5. Obesity</h3>
            <p>Excess weight increases the risk of sleep apnea and other sleep problems.</p>

            <h3>6. Neurological Conditions</h3>
            <p>Conditions like Parkinson's disease and Alzheimer's can affect sleep patterns.</p>

            <h2>Symptoms of Sleep Disorders</h2>
            <p>Symptoms vary depending on the type of disorder:</p>
            <ul>
                <li>Difficulty falling or staying asleep</li>
                <li>Excessive daytime sleepiness</li>
                <li>Loud snoring</li>
                <li>Breathing interruptions during sleep</li>
                <li>Restless legs</li>
                <li>Unusual behaviors during sleep</li>
                <li>Fatigue and low energy</li>
                <li>Difficulty concentrating</li>
                <li>Irritability and mood changes</li>
            </ul>
            <p>If sleep problems persist for more than a few weeks, consult a neurologist.</p>

