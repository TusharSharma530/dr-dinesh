            <h2>What is Migraine?</h2>
            <p>Migraine is a type of headache that usually occurs on one side of the head and can last from a few hours to several days. It is often accompanied by throbbing or pulsating pain that worsens with physical activity.</p>
            <p>Migraine may affect:</p>
