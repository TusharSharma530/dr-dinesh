            <h2>Stroke Treatment Options</h2>
            <p>Treatment depends on the type and severity of stroke.</p>

            <h3>Medications</h3>
            <p>Blood clot-busting drugs (tPA), antiplatelet medicines, and anticoagulants may be prescribed to dissolve clots or prevent new ones from forming.</p>

            <h3>Surgery</h3>
            <p>In severe cases, surgical procedures like carotid endarterectomy or stenting may be required to remove blockages.</p>

            <h3>Physiotherapy & Rehabilitation</h3>
            <p>Physical therapy, occupational therapy, and speech therapy help patients recover movement, daily skills, and communication abilities.</p>

            <h3>Life Style Changes</h3>
            <p>Managing blood pressure, quitting smoking, exercising regularly, and eating a healthy diet are essential for long-term recovery and prevention.</p>

