            <h2>What are Neuromuscular Disorders?</h2>
            <p>Neuromuscular disorders are a group of conditions that affect the peripheral nerves, muscles, or the junction between them (neuromuscular junction). These disorders can be inherited or acquired.</p>
            <p>Common conditions include:</p>
            <ul>
                <li>Muscular Dystrophy</li>
                <li>Myasthenia Gravis</li>
                <li>Amyotrophic Lateral Sclerosis (ALS)</li>
