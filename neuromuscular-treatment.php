            <h2>Common Causes of Neuromuscular Disorders</h2>

            <h3>1. Genetic Factors</h3>
            <p>Many neuromuscular disorders are inherited and passed through families.</p>

            <h3>2. Autoimmune Conditions</h3>
            <p>The immune system mistakenly attacks the neuromuscular junction, as in Myasthenia Gravis.</p>

            <h3>3. Infections</h3>
            <p>Viral and bacterial infections can damage nerves and muscles.</p>

            <h3>4. Metabolic Disorders</h3>
            <p>Conditions affecting metabolism can lead to muscle weakness.</p>

            <h3>5. Toxins and Medications</h3>
            <p>Exposure to certain toxins or side effects of medications may cause nerve damage.</p>

            <h3>6. Trauma</h3>
            <p>Physical injury to nerves can result in neuromuscular problems.</p>

